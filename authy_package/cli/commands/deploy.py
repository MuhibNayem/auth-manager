@deploy_cmd.command("kubernetes")
@click.option("--namespace", "-n", default="authy", show_default=True)
@click.option("--replicas", default=3, show_default=True)
@click.option("--image", default="authy-app:latest", show_default=True)
def kubernetes(namespace: str, replicas: int, image: str):
    """Generate Kubernetes manifests into ./deploy-out/k8s/ (no cluster calls)."""
    try:
        import yaml
    except ImportError:
        console.print("[red]✗ PyYAML is required to generate artifacts[/red]")
        raise click.exceptions.Exit(1)

    ns = {
        "apiVersion": "v1",
        "kind": "Namespace",
        "metadata": {"name": namespace},
    }
    deployment = {
        "apiVersion": "apps/v1",
        "kind": "Deployment",
        "metadata": {"name": "authy", "namespace": namespace},
        "spec": {
            "replicas": replicas,
            "selector": {"matchLabels": {"app": "authy"}},
            "template": {
                "metadata": {"labels": {"app": "authy"}},
                "spec": {
                    "containers": [
                        {
                            "name": "authy",
                            "image": image,
                            "ports": [{"containerPort": 8000}],
                        }
                    ]
                },
            },
        },
    }
    service = {
        "apiVersion": "v1",
        "kind": "Service",
        "metadata": {"name": "authy", "namespace": namespace},
        "spec": {
            "selector": {"app": "authy"},
            "ports": [{"port": 80, "targetPort": 8000}],
        },
    }

    written: List[Path] = [
        _write_artifact(DEPLOY_OUT_DIR / "k8s" / "namespace.yaml", yaml.safe_dump(ns)),
        _write_artifact(DEPLOY_OUT_DIR / "k8s" / "deployment.yaml", yaml.safe_dump(deployment)),
        _write_artifact(DEPLOY_OUT_DIR / "k8s" / "service.yaml", yaml.safe_dump(service)),
    ]
    for path in written:
        console.print(f"[green]✓ Generated manifest:[/green] {path}")
    console.print(
        "[dim]Apply yourself with `kubectl apply -f deploy-out/k8s/`. "
        "No cluster resources were created.[/dim]"
    )
